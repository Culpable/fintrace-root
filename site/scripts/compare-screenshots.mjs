// Compares candidate screenshots against the production references and writes
// the diff images. Usage: node scripts/compare-screenshots.mjs [name ...]
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import pixelmatch from 'pixelmatch'
import sharp from 'sharp'

const repo = resolve(import.meta.dirname, '../..')
const referenceDirectory = resolve(repo, 'documents/guides/parity/screenshots/production')
const candidateDirectory = resolve(repo, 'documents/guides/parity/screenshots/candidate')
const diffDirectory = resolve(repo, 'documents/guides/parity/screenshots/diff')
mkdirSync(diffDirectory, { recursive: true })

// The hero WebGL canvas and the trace canvas render different pixels on every
// frame, so both are excluded by rectangle before the comparison. The fixed
// skip link is excluded too: Chromium's full-page capture places it inside the
// document on the contact interaction states.
const MAX_DIFFERING_RATIO = 0.01
const PIXELMATCH_THRESHOLD = 0.1

/**
 * `/privacy/` carries the only approved copy change (plan D-13): the hosting
 * paragraph now names Cloudflare and the analytics paragraph discloses the
 * session-storage queue. Both sit below the "Information handled by this site"
 * heading, so everything under it legitimately reflows and the page grows.
 * The comparison therefore covers the identical region above that heading; the
 * changed copy itself is verified word for word by `compare-text.mjs`.
 */
const COMPARE_HEIGHT_LIMIT = {
  'privacy-desktop': 801,
  'privacy-mobile': 926,
}

const names =
  process.argv.slice(2).length > 0
    ? process.argv.slice(2)
    : readdirSync(referenceDirectory)
        .filter((file) => file.endsWith('.webp'))
        .map((file) => file.replace(/\.webp$/, ''))

async function loadRaw(path) {
  const image = sharp(path).ensureAlpha()
  const { data, info } = await image.raw().toBuffer({ resolveWithObject: true })
  return { data, width: info.width, height: info.height }
}

let failures = 0
for (const name of names) {
  const reference = await loadRaw(resolve(referenceDirectory, `${name}.webp`))
  const candidate = await loadRaw(resolve(candidateDirectory, `${name}.webp`))

  const width = Math.min(reference.width, candidate.width)
  const limit = COMPARE_HEIGHT_LIMIT[name]
  const height = Math.min(reference.height, candidate.height, limit ?? Number.POSITIVE_INFINITY)
  const sizeMismatch =
    limit === undefined && (reference.width !== candidate.width || reference.height !== candidate.height)

  const crop = async (path) =>
    (await sharp(path).ensureAlpha().extract({ left: 0, top: 0, width, height }).raw().toBuffer({ resolveWithObject: true })).data

  const needsCrop = reference.width !== width || reference.height !== height || candidate.width !== width || candidate.height !== height
  const referenceData = needsCrop ? await crop(resolve(referenceDirectory, `${name}.webp`)) : reference.data
  const candidateData = needsCrop ? await crop(resolve(candidateDirectory, `${name}.webp`)) : candidate.data

  const diff = Buffer.alloc(width * height * 4)
  const differing = pixelmatch(referenceData, candidateData, diff, width, height, {
    threshold: PIXELMATCH_THRESHOLD,
    includeAA: false,
  })
  const ratio = differing / (width * height)

  await sharp(diff, { raw: { width, height, channels: 4 } }).png().toFile(resolve(diffDirectory, `${name}.png`))

  const verdict = ratio <= MAX_DIFFERING_RATIO && !sizeMismatch ? 'PASS' : 'FAIL'
  if (verdict === 'FAIL') failures += 1
  process.stdout.write(
    `${verdict} ${name.padEnd(28)} ${(ratio * 100).toFixed(3)}% of ${width}x${height}` +
      (limit ? ` (compared above the D-13 copy change)` : '') +
      (sizeMismatch ? ` (size ${reference.width}x${reference.height} vs ${candidate.width}x${candidate.height})` : '') +
      '\n',
  )
}

writeFileSync(resolve(diffDirectory, 'README.md'), '# Parity diff images\n\nGenerated by `site/scripts/compare-screenshots.mjs`. Regenerated on every parity run.\n')
process.exit(failures === 0 ? 0 : 1)
